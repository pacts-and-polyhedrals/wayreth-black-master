/**
 * Renders ROBE-SPELL-CATALOGUE.md from content/spells.json.
 *
 * The catalogue used to be maintained by hand, and the 1.28.0 rebalance found
 * it still quoting figures the module had moved past — Borrowed Vitality's old
 * 2d6 among them. A review document that disagrees with the module is worse
 * than no review document, so it is generated now and checked by the
 * validator, which fails if the committed file is stale.
 */
import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
const SOURCE = path.join(ROOT, "content", "spells.json");
const OUT = path.join(ROOT, "ROBE-SPELL-CATALOGUE.md");

const ORDERS = ["White", "Red", "Black"];
const CIRCLES = ["Cantrip", "1st-level", "2nd-level", "3rd-level", "4th-level",
                 "5th-level", "6th-level", "7th-level", "8th-level", "9th-level"];
const SCHOOLS = {
  abj: "Abjuration", con: "Conjuration", div: "Divination", enc: "Enchantment",
  evo: "Evocation", ill: "Illusion", nec: "Necromancy", trs: "Transmutation"
};

const prose = html => String(html)
  .replace(/<\/p>\s*<p>/g, "\n\n")
  .replace(/<li>/g, "\n- ")
  .replace(/<[^>]+>/g, "")
  .replace(/&#x27;/g, "'")
  .replace(/&amp;/g, "&")
  .replace(/&mdash;/g, "—")
  .replace(/&nbsp;/g, " ")
  .replace(/[ \t]+/g, " ")
  .replace(/ *\n */g, "\n")
  .replace(/\n{3,}/g, "\n\n")
  .trim();

const section = (html, heading) => {
  const found = new RegExp(`<h3>${heading}</h3>([\\s\\S]*?)(?=<h3>|<div class="wy-quote">|$)`).exec(html);
  return found ? prose(found[1]) : "";
};

const rows = html => [...html.matchAll(/<tr><th>([^<]+)<\/th><td>([\s\S]*?)<\/td><\/tr>/g)]
  .map(([, key, value]) => [key, prose(value)]);

export function render(doc) {
  const out = [
    "# The Robe Spellbooks of High Sorcery",
    "",
    `Complete review catalogue, generated from \`content/spells.json\`: ${doc.items.length} spells, ${doc.items.length / 3} per Order. ` +
    "Spells marked **Legacy conversion** are 5e rebuilds of the supplied 3.5e material; the rest were written for this module. " +
    "Do not edit this file — run `npm run build:catalogue`.",
    ""
  ];

  for (const order of ORDERS) {
    out.push(`# ${order} Robes`, "");
    const mine = doc.items.filter(s => s.flags?.["wayreth-black-master"]?.order === order);
    for (let level = 0; level <= 9; level += 1) {
      const atLevel = mine.filter(s => s.system.level === level)
        .sort((a, b) => a.name.localeCompare(b.name));
      if (!atLevel.length) continue;
      out.push(`## ${CIRCLES[level]} spells`, "");
      for (const spell of atLevel) {
        const html = spell.system.description.value;
        const legacy = spell.flags["wayreth-black-master"].legacyConversion === true;
        const school = SCHOOLS[spell.system.school] ?? spell.system.school;
        out.push(`### ${spell.name}`, "");
        out.push(`**${school} · ${CIRCLES[level]} · ${order} Robe · ${legacy ? "Legacy conversion" : "Wayreth original"}**`, "");
        for (const [key, value] of rows(html)) {
          if (key === "Circle") continue; // already in the line above
          out.push(`- **${key}:** ${value}`);
        }
        out.push("");
        const effect = section(html, "Effect");
        if (effect) out.push(effect, "");
        for (const extra of ["At Higher Levels", "Higher Levels", "Notes"]) {
          const text = section(html, extra);
          if (text) out.push(`**${extra}.** ${text}`, "");
        }
      }
    }
  }
  return `${out.join("\n").replace(/\n{3,}/g, "\n\n").trimEnd()}\n`;
}

const doc = JSON.parse(fs.readFileSync(SOURCE, "utf8"));
const text = render(doc);

if (process.argv.includes("--check")) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (current !== text) {
    console.error("ROBE-SPELL-CATALOGUE.md is out of date. Run: npm run build:catalogue");
    process.exit(1);
  }
  console.log("Spell catalogue is current.");
} else {
  fs.writeFileSync(OUT, text);
  console.log(`Wrote ROBE-SPELL-CATALOGUE.md — ${doc.items.length} spells, ${text.length} characters.`);
}
